export function isUnicodeEmojiIcon(value) {
  const s = String(value || "");
  if (!s || s.length > 16) return false;
  if (/^[a-z0-9][a-z0-9_-]{1,31}$/i.test(s)) return false;
  try {
    return /\p{Extended_Pictographic}/u.test(s);
  } catch {
    return /[^\u0000-\u00ff]/.test(s);
  }
}

export function resolveKnowledgeIcon(icon, emojiMap) {
  if (!icon) return { type: "none" };
  const raw = String(icon);
  const custom = emojiMap?.get(raw.toLowerCase());
  if (custom) return { type: "custom", emoji: custom };
  if (isUnicodeEmojiIcon(raw)) return { type: "unicode", char: raw };
  return { type: "none" };
}
